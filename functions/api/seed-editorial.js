export async function onRequestPost({ request, env }) {
  if (!checkAuth(request, env)) return jsonResponse({ error: 'Неоторизиран достъп.' }, 401);
  try {
    const date = new Date().toISOString().slice(0,10);
    for (const r of recipes) {
      await env.DB.prepare(`INSERT INTO recipes
        (id, source_id, title, title_en, excerpt, ingredients, instructions, category, area, diet_tags, image, youtube, author, date, featured, time)
        VALUES (?, ?, ?, NULL, ?, ?, ?, ?, ?, ?, ?, NULL, ?, ?, 0, ?)
        ON CONFLICT(source_id) DO UPDATE SET
          title=excluded.title, excerpt=excluded.excerpt, ingredients=excluded.ingredients,
          instructions=excluded.instructions, category=excluded.category, area=excluded.area,
          diet_tags=excluded.diet_tags, image=excluded.image, author=excluded.author,
          date=excluded.date, time=excluded.time`)
        .bind(
          r.id, r.source_id, r.title, r.excerpt, JSON.stringify(r.ingredients), r.instructions,
          r.category, r.area, 'домашно,авторска рецепта', r.image, 'Готвач БГ', date, r.time
        ).run();
    }
    return jsonResponse({ ok:true, count:recipes.length, titles:recipes.map(r=>r.title) });
  } catch (e) {
    return jsonResponse({ error:'Неуспешно записване: '+String(e?.message||e) },500);
  }
}
